    private static string LocalizeEnglish(string name)
    {
        if (string.IsNullOrWhiteSpace(name)) return name;
        if (EnglishNames.TryGetValue(name, out var english)) return english;
        return name;
    }

    internal static string LocalizeForTest(string name) => LocalizeEnglish(name);
    public static string SkillName(int raw)
    {
        EnsureLoaded();
        if (skills is not null)
        {
            if (skills.TryGetValue(raw, out var exact)) return LocalizeEnglish(exact);
            int r10 = raw / 10 * 10;
            if (r10 != raw && skills.TryGetValue(r10, out var n10)) return LocalizeEnglish(n10);
            int r10k = raw / 10000 * 10000;
            if (r10k != raw && skills.TryGetValue(r10k, out var n10k)) return LocalizeEnglish(n10k);
            // Observed combat IDs encode rank/variant data in the low digits.
            // Example: 11010340 -> public catalog base 11010000.
            int r100k = raw / 100000 * 100000;
            if (r100k != raw && skills.TryGetValue(r100k, out var n100k)) return LocalizeEnglish(n100k);
        }
        return "Skill " + raw;
    }

    public static string? MobName(int code)
    {
        EnsureLoaded();
        // Prefer the English NPC catalogue by numeric mob/template code. This prevents
        // Korean bootstrap names from reaching the overlay at all.
        if (englishMobs is not null && englishMobs.TryGetValue(code, out var english))
            return EnglishTargetLabel(english);
        if (mobs is not null && mobs.TryGetValue(code, out var name))
            return EnglishTargetLabel(LocalizeEnglish(name));
        return null;
    }

    internal static string? EnglishTargetLabel(string? name)
    {
        // Unknown localized NPC text must fall back to Target <entity>, never a guessed translation.
        if(string.IsNullOrWhiteSpace(name) || name.Any(c=>char.IsLetter(c) && c>'\u024F'))return null;
        return name;
    }

    private static void EnsureLoaded()
    {
        if (attempted) return;
        lock (Sync)
        {
            if (attempted) return;
            attempted = true;
            string? json = null;
            try
            {
                using var http = new HttpClient { Timeout = TimeSpan.FromSeconds(5) };
                json = http.GetStringAsync("https://api.aion2meter.com/api/gamedata/meter-bootstrap").GetAwaiter().GetResult();
                Directory.CreateDirectory(Path.GetDirectoryName(CachePath)!);
                File.WriteAllText(CachePath, json);
            }
            catch
            {
                try { if (File.Exists(CachePath)) json = File.ReadAllText(CachePath); } catch { }
            }
            // English NPC names are an independent source. Load them even when
            // meter-bootstrap is temporarily unavailable or changes JSON shape.
            // Otherwise a bootstrap outage degrades every known NPC to Target <entity>.
            englishMobs = LoadEnglishMobCatalog();

            if (string.IsNullOrWhiteSpace(json)) return;
            try
            {
                using var doc = JsonDocument.Parse(json);
                var map = new Dictionary<int,string>();
                // meter-bootstrap has changed shape over time. Walk the JSON
                // recursively and accept either {code,name} or {id,name}.
                CollectSkills(doc.RootElement, map);
                skills = map;
                var mobMap = new Dictionary<int,string>();
                CollectMobs(doc.RootElement, mobMap, false);
                mobs = mobMap;
            }
            catch { }
        }
    }

    private static Dictionary<int,string> LoadEnglishMobCatalog()
    {
        var map = new Dictionary<int,string>();
        try
        {
            using var http = new HttpClient { Timeout = TimeSpan.FromSeconds(5) };
            var json = http.GetStringAsync("https://raw.githubusercontent.com/Helveticxa/Aether-Aion2-DPS-meter-Global/main/src-tauri/data/npc_names_en.json").GetAwaiter().GetResult();
            using var doc = JsonDocument.Parse(json);
            foreach (var p in doc.RootElement.EnumerateObject())
                if (int.TryParse(p.Name, out var id) && p.Value.ValueKind == JsonValueKind.String)
                {
                    var name = p.Value.GetString();
                    if (!string.IsNullOrWhiteSpace(name)) map[id] = name;
                }
        }
        catch { }
        return map;
    }

    private static void CollectMobs(JsonElement node, Dictionary<int,string> map, bool insideMobs)
    {
        if (node.ValueKind == JsonValueKind.Object)
        {
            bool nowInside = insideMobs;
            foreach (var p in node.EnumerateObject())
                if (p.Name.Equals("mobs", StringComparison.OrdinalIgnoreCase)) nowInside = true;

            if (nowInside)
            {
                int code = 0;
                string? name = null;
                foreach (var p in node.EnumerateObject())
                {
                    if ((p.Name.Equals("id", StringComparison.OrdinalIgnoreCase) ||
                         p.Name.Equals("code", StringComparison.OrdinalIgnoreCase)) &&
                        p.Value.ValueKind == JsonValueKind.Number)
                        p.Value.TryGetInt32(out code);
                    else if (p.Name.Equals("name", StringComparison.OrdinalIgnoreCase) &&
                             p.Value.ValueKind == JsonValueKind.String)
                        name = p.Value.GetString();
                }
                if (code > 0 && !string.IsNullOrWhiteSpace(name)) map[code] = name;
            }
            foreach (var p in node.EnumerateObject())
                CollectMobs(p.Value, map, insideMobs || p.Name.Equals("mobs", StringComparison.OrdinalIgnoreCase));
        }
        else if (node.ValueKind == JsonValueKind.Array)
            foreach (var item in node.EnumerateArray()) CollectMobs(item, map, insideMobs);
    }

    private static void CollectSkills(JsonElement node, Dictionary<int,string> map)
    {
        if (node.ValueKind == JsonValueKind.Object)
        {
            int code = 0;
            if (node.TryGetProperty("code", out var c)) c.TryGetInt32(out code);
            if (code == 0 && node.TryGetProperty("id", out var id)) id.TryGetInt32(out code);
            if (code > 0 && node.TryGetProperty("name", out var n))
            {
                var name = n.GetString();
                if (!string.IsNullOrWhiteSpace(name)) map[code] = name;
            }
            foreach (var p in node.EnumerateObject()) CollectSkills(p.Value, map);
        }
        else if (node.ValueKind == JsonValueKind.Array)
            foreach (var item in node.EnumerateArray()) CollectSkills(item, map);
    }
